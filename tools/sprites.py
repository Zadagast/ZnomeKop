"""Player sprite assembly and hand-authored seamless fill tiles.

Player art lives in assets/player/ as curated 1-bit PNGs (one per facing).
Walk frames are derived from each base pose with a deliberate leg shift,
which keeps the character identical between frames.

Fill tiles must tile invisibly across large areas, so they are authored
here as explicit pixel maps rather than generated.

Legend for pixel maps: '#' = black ink, '.' = white
"""

from __future__ import annotations

from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
PLAYER_DIR = ROOT / "assets" / "player"

T = 32


# ------------------------------------------------------------------ player --

def _load_facing(name: str) -> Image.Image:
    path = PLAYER_DIR / f"{name}.png"
    if not path.is_file():
        raise SystemExit(f"Missing player sprite: {path}")
    im = Image.open(path).convert("1")
    if im.size != (T, T):
        raise SystemExit(f"{path} must be {T}x{T}, got {im.size}")
    return im


def _ink_bounds(im: Image.Image) -> tuple[int, int]:
    """Top and bottom rows containing ink."""
    px = im.load()
    rows = [y for y in range(T) if any(px[x, y] == 0 for x in range(T))]
    return (rows[0], rows[-1]) if rows else (0, T - 1)


def _walk_frame(im: Image.Image, shift: int) -> Image.Image:
    """Second walk frame: legs step sideways, body bobs up one pixel."""
    top, bottom = _ink_bounds(im)
    leg_top = max(top, bottom - 5)

    out = Image.new("1", (T, T), 1)
    # body lifted 1px
    body = im.crop((0, 0, T, leg_top))
    out.paste(body, (0, -1))
    # legs shifted sideways, staying on the ground line
    legs = im.crop((0, leg_top, T, T))
    out.paste(legs, (shift, 0 + leg_top - 1))
    return out


def player_frames() -> list[Image.Image]:
    """8 frames: down x2, up x2, left x2, right x2."""
    down = _load_facing("down")
    up = _load_facing("up")
    left = _load_facing("left")
    right = _load_facing("right")
    return [
        down, _walk_frame(down, 1),
        up, _walk_frame(up, -1),
        left, _walk_frame(left, 1),
        right, _walk_frame(right, -1),
    ]


# ------------------------------------------------------- seamless fill tiles --

def parse(grid: str, size: int = T) -> Image.Image:
    rows = [r for r in grid.strip().splitlines()]
    assert len(rows) == size, f"need {size} rows, got {len(rows)}"
    img = Image.new("1", (size, size), 1)
    px = img.load()
    for y, row in enumerate(rows):
        assert len(row) == size, f"row {y} has {len(row)} cols, need {size}"
        for x, ch in enumerate(row):
            if ch == "#":
                px[x, y] = 0
    return img


