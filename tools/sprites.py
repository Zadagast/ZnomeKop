"""Player sprite assembly and hand-authored seamless fill tiles.

Player art lives in assets/player/ as curated 1-bit PNGs (one per facing).
Walk frames are derived from each base pose with a deliberate leg shift,
which keeps the character identical between frames.

Fill tiles must tile invisibly across large areas, so they are authored
here as explicit pixel maps rather than generated.

Legend for pixel maps: '#' = black ink, '.' = white
"""

from __future__ import annotations

from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
PLAYER_DIR = ROOT / "assets" / "player"

T = 32


# ------------------------------------------------------------------ player --

def _load_facing(name: str) -> Image.Image:
    path = PLAYER_DIR / f"{name}.png"
    if not path.is_file():
        raise SystemExit(f"Missing player sprite: {path}")
    im = Image.open(path).convert("1")
    if im.size != (T, T):
        raise SystemExit(f"{path} must be {T}x{T}, got {im.size}")
    return im


# Walk cycle. The curated sprites are outline art, so step poses are derived
# from the real legs rather than redrawn: one leg lifts a pixel while the
# other stays planted. Head and torso are untouched, so the character never
# changes shape between frames.

LEG_TOP = 26   # first row that is leg rather than hip
LEG_SPLIT = 16  # column dividing the two legs


def _step_frame(base: Image.Image, lift_left: bool) -> Image.Image:
    """Raise one boot by a pixel; the other keeps contact with the ground."""
    out = base.copy()
    x0, x1 = (0, LEG_SPLIT) if lift_left else (LEG_SPLIT, T)

    leg = base.crop((x0, LEG_TOP, x1, T))
    # Clear the half we are about to redraw.
    blank = Image.new("1", (x1 - x0, T - LEG_TOP), 1)
    out.paste(blank, (x0, LEG_TOP))
    # Redraw it one pixel higher, so the knee bends and the boot comes up.
    out.paste(leg, (x0, LEG_TOP - 1), leg.point(lambda p: 255 if p == 0 else 0, mode="1"))
    return out


def player_frames() -> list[Image.Image]:
    """12 frames: neutral, step-left, step-right for down, up, left, right."""
    frames: list[Image.Image] = []
    for name in ("down", "up", "left"):
        base = _load_facing(name)
        frames.extend([base, _step_frame(base, True), _step_frame(base, False)])

    # Right facing mirrors left, including its step poses.
    left_frames = frames[6:9]
    frames.extend(f.transpose(Image.FLIP_LEFT_RIGHT) for f in left_frames)
    return frames


# ------------------------------------------------------- seamless fill tiles --

def parse(grid: str, size: int = T) -> Image.Image:
    rows = [r for r in grid.strip().splitlines()]
    assert len(rows) == size, f"need {size} rows, got {len(rows)}"
    img = Image.new("1", (size, size), 1)
    px = img.load()
    for y, row in enumerate(rows):
        assert len(row) == size, f"row {y} has {len(row)} cols, need {size}"
        for x, ch in enumerate(row):
            if ch == "#":
                px[x, y] = 0
    return img


def _rock_hatch(img: Image.Image, y0: int, y1: int) -> None:
    """Diagonal hatch: heavy enough to read as stone, light enough to stay 1-bit clean."""
    px = img.load()
    for y in range(y0, y1 + 1):
        for x in range(T):
            if (x + y) % 4 == 0 or (x - y) % 8 == 0:
                px[x, y] = 0


