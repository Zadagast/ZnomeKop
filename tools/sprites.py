def ground_variants() -> list[Image.Image]:
    return [parse(GROUND_A), parse(GROUND_B), parse(GROUND_C)]


def strata_tile() -> Image.Image:
    return parse(STRATA)


def cliff_top_tile() -> Image.Image:
    """Plateau rim: bold cap edge over hatched stone."""
    img = parse(CLIFF_TOP)
    _rock_hatch(img, 4, T - 1)
    px = img.load()
    for y in range(0, 4):
        for x in range(T):
            px[x, y] = 0
    return img


def cliff_face_tile() -> Image.Image:
    """Cliff body: hatched stone with vertical fractures."""
    img = parse(CLIFF_FACE)
    _rock_hatch(img, 0, T - 1)
    return img


# Roads are defined by their kerbs rather than surface texture, so a one-tile
# route still reads as a road against calm regolith. One tile exists for each
# combination of neighbouring route cells; kerbs are drawn only on the sides
# that open onto terrain, which keeps corners and junctions continuous.

ROUTE_UP, ROUTE_RIGHT, ROUTE_DOWN, ROUTE_LEFT = 1, 2, 4, 8


def route_tile_for_mask(mask: int) -> Image.Image:
    """mask bits mark sides that connect to another route cell."""
    img = Image.new("1", (T, T), 1)
    px = img.load()

    def dash_h(y: int) -> None:
        for x in range(T):
            if x % 3 != 2:
                px[x, y] = 0

    def dash_v(x: int) -> None:
        for y in range(T):
            if y % 3 != 2:
                px[x, y] = 0

    if not mask & ROUTE_UP:
        dash_h(0)
    if not mask & ROUTE_DOWN:
        dash_h(T - 1)
    if not mask & ROUTE_LEFT:
        dash_v(0)
    if not mask & ROUTE_RIGHT:
        dash_v(T - 1)
    return img


def route_tiles() -> list[Image.Image]:
    """All 16 connectivity variants, indexed by mask."""
    return [route_tile_for_mask(m) for m in range(16)]


def plaza_tile() -> Image.Image:
    return parse(PLAZA)


