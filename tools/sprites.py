def ground_variants() -> list[Image.Image]:
    return [parse(GROUND_A), parse(GROUND_B), parse(GROUND_C)]


def strata_tile() -> Image.Image:
    return parse(STRATA)


def cliff_top_tile() -> Image.Image:
    """Plateau rim: bold cap edge over hatched stone."""
    img = parse(CLIFF_TOP)
    _rock_hatch(img, 4, T - 1)
    px = img.load()
    for y in range(0, 4):
        for x in range(T):
            px[x, y] = 0
    return img


def cliff_face_tile() -> Image.Image:
    """Cliff body: hatched stone with vertical fractures."""
    img = parse(CLIFF_FACE)
    _rock_hatch(img, 0, T - 1)
    return img


def route_tile() -> Image.Image:
    return parse(ROUTE)


def plaza_tile() -> Image.Image:
    return parse(PLAZA)


